    def _get_dashboard_js(self) -> str:
        """Get JavaScript for dashboard functionality."""
        return """
        // Initialize dashboard
        document.addEventListener('DOMContentLoaded', function() {
            document.getElementById('timestamp').textContent = 'Generated: ' + new Date().toLocaleString();
            renderMetrics();
            renderCharts();
            renderDataTable();
        });

        function renderMetrics() {
            const container = document.getElementById('metricsGrid');
            if (!METRICS || METRICS.length === 0) {
                container.innerHTML = '<div class="loading">No metrics available</div>';
                return;
            }

            const html = METRICS.map(metric => `
                <div class="metric-card">
                    ${metric.icon ? `<div class="metric-icon" style="color: ${metric.color || '#4299e1'};"><i class="${metric.icon}"></i></div>` : ''}
                    <div class="metric-label">${metric.label}</div>
                    <div class="metric-value" style="color: ${metric.color || '#4299e1'};">${metric.value}</div>
                    ${metric.change ? `<div class="metric-change" style="color: ${metric.change > 0 ? 'var(--success)' : 'var(--danger)'};">${metric.change > 0 ? '↗' : '↘'} ${Math.abs(metric.change)}%</div>` : ''}
                </div>
            `).join('');

            container.innerHTML = html;
        }

        function renderCharts() {
            const container = document.getElementById('chartsContainer');
            if (!CHARTS || CHARTS.length === 0) {
                container.innerHTML = '<div class="loading">No charts configured</div>';
                return;
            }

            const chartsHtml = CHARTS.map((chart, index) => `
                <div class="chart-container">
                    <div class="chart-title">
                        ${chart.icon ? `<i class="${chart.icon}"></i>` : '<i class="fas fa-chart-bar"></i>'}
                        ${chart.title}
                    </div>
                    <div id="chart-${index}" style="height: ${chart.height || '400px'};"></div>
                </div>
            `).join('');

            container.innerHTML = chartsHtml;

            // Render each chart
            CHARTS.forEach((chart, index) => {
                renderChart(chart, `chart-${index}`);
            });
        }

        function renderChart(config, elementId) {
            const data = DATA;
            let traces = [];
            let layout = config.layout || {};

            switch(config.type) {
                case 'bar':
                    traces = [{
                        x: data.map(d => d[config.x_key]),
                        y: data.map(d => parseFloat(d[config.y_key]) || 0),
                        type: 'bar',
                        name: config.series_name || config.y_key,
                        marker: { 
                            color: config.colors || data.map(d => getColorForValue(d[config.color_key || config.y_key]))
                        }
                    }];
                    break;

                case 'line':
                    traces = [{
                        x: data.map(d => d[config.x_key]),
                        y: data.map(d => parseFloat(d[config.y_key]) || 0),
                        type: 'scatter',
                        mode: 'lines+markers',
                        name: config.series_name || config.y_key,
                        line: { color: config.color || '#4299e1', width: 3 }
                    }];
                    break;

                case 'scatter':
                    traces = [{
                        x: data.map(d => parseFloat(d[config.x_key]) || 0),
                        y: data.map(d => parseFloat(d[config.y_key]) || 0),
                        mode: 'markers+text',
                        type: 'scatter',
                        text: data.map(d => d[config.text_key] || ''),
                        textposition: 'top center',
                        marker: {
                            size: 12,
                            color: data.map(d => getColorForValue(d[config.color_key])),
                            line: { width: 2, color: 'white' }
                        }
                    }];
                    break;

                case 'pie':
                    traces = [{
                        values: data.map(d => parseFloat(d[config.value_key]) || 0),
                        labels: data.map(d => d[config.label_key]),
                        type: 'pie',
                        hole: config.donut ? 0.4 : 0,
                        marker: {
                            colors: config.colors || data.map((_, i) => `hsl(${i * 360 / data.length}, 70%, 50%)`)
                        }
                    }];
                    break;

                default:
                    console.warn('Unknown chart type:', config.type);
                    return;
            }

            // Default layout settings
            const defaultLayout = {
                margin: { t: 30, r: 30, b: 60, l: 60 },
                font: { family: '-apple-system, BlinkMacSystemFont, Segoe UI, system-ui, sans-serif' },
                paper_bgcolor: 'rgba(0,0,0,0)',
                plot_bgcolor: 'rgba(0,0,0,0)'
            };

            const finalLayout = Object.assign(defaultLayout, layout);
            
            Plotly.newPlot(elementId, traces, finalLayout, {
                responsive: true,
                displayModeBar: false
            });
        }

        function renderDataTable() {
            const container = document.getElementById('dataTable');
            if (!DATA || DATA.length === 0) {
                container.innerHTML = '<div class="loading">No data available</div>';
                return;
            }

            const headers = Object.keys(DATA[0]);
            const tableHtml = `
                <table class="data-table">
                    <thead>
                        <tr>${headers.map(h => `<th>${h.replace(/_/g, ' ').toUpperCase()}</th>`).join('')}</tr>
                    </thead>
                    <tbody>
                        ${DATA.map(row => `
                            <tr>
                                ${headers.map(h => `<td>${formatCellValue(row[h], h)}</td>`).join('')}
                            </tr>
                        `).join('')}
                    </tbody>
                </table>
            `;

            container.innerHTML = tableHtml;
        }

        function formatCellValue(value, header) {
            if (header.toLowerCase().includes('risk')) {
                return `<span class="status-badge status-${value.toLowerCase()}">${value}</span>`;
            }
            if (header.toLowerCase().includes('pct') || header.toLowerCase().includes('percent')) {
                return value + '%';
            }
            return value || '';
        }

        function getColorForValue(value) {
            if (typeof value === 'string') {
                switch(value.toLowerCase()) {
                    case 'high': return '#e53e3e';
                    case 'medium': case 'med': return '#dd6b20';
                    case 'low': return '#38a169';
                    default: return '#4299e1';
                }
            }
            
            const v = parseFloat(value);
            if (isNaN(v)) return '#718096';
            if (v >= 80) return '#38a169';
            if (v >= 60) return '#dd6b20';
            return '#e53e3e';
        }
        """

    def launch_instructions(self, dashboard_path: Path, csv_path: Optional[Path] = None) -> List[str]:
        """Generate user instructions for viewing dashboard."""
        instructions = [
            f"🚀 VIEW INTERACTIVE DASHBOARD:",
            f"   📊 Dashboard: {dashboard_path.name}",
        ]
        
        if csv_path:
            instructions.append(f"   📈 Raw Data: {csv_path.name}")
            
        instructions.extend([
            f"",
            f"💡 VIEWING OPTIONS:",
            f"   1. Install 'Live Server' extension in VS Code",
            f"   2. Right-click dashboard → 'Open with Live Server'",
            f"   3. Or open file directly in browser",
            f"",
            f"📋 ALTERNATIVE TOOLS:",
            f"   • Excel Viewer extension for CSV files",
            f"   • Rainbow CSV for color-coded data",
            f"   • Data Preview extension for inline charts"
        ])
        
        return instructions
