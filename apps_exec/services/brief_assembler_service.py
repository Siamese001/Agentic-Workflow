"""
Brief Assembler Service — apps_exec

Assembles executive briefs from synthesized content.
Aligned with apps_lic service pattern with lifecycle trace integration.
"""

from __future__ import annotations

import logging
from typing import Any

from agentic_core.runtime.lifecycle_trace_contract import (
    LayerSegment,
    _emit_records_execution_trace,
    _emit_records_telemetry_event,
    _emit_routes_to_capability,
    _emit_snapshots_state,
    _emit_writes_via_uwg,
)

_log = logging.getLogger(__name__)


class BriefAssemblerService:
    """Service for assembling executive briefs."""

    def __init__(self, config: dict[str, Any] | None = None) -> None:
        """Initialize the brief assembler service."""
        self.config = config or {}
        self._brief_template = {
            "header": "# Executive Brief\n\n",
            "sections": [],
            "footer": "\n---\n*Generated by Agentic Workflow Platform*",
        }
        _emit_snapshots_state("p0", "brief_assembler", "init")

    def assemble_brief(
        self,
        content_sections: list[dict[str, Any]],
        persona_id: str = "recruiter",
        target_word_count: int = 600,
    ) -> dict[str, Any]:
        """Assemble a complete brief from content sections.

        Args:
            content_sections: List of section content dicts
            persona_id: Target persona identifier
            target_word_count: Target word count

        Returns:
            Assembled brief metadata and content
        """
        import uuid as _uuid  # noqa: PLC0415

        _trace_id = str(_uuid.uuid4())
        _emit_records_execution_trace(
            _trace_id, LayerSegment.L2_EXECUTION, "BriefAssemblerService.assemble_brief"
        )
        _emit_routes_to_capability("p2", "brief_assembler", "content_synthesis")
        _emit_writes_via_uwg("p2", "brief_assembler", "brief_output")
        _emit_records_telemetry_event("p4", "brief_assembler", "assembly_start")

        # Assemble sections
        assembled_sections: list[str] = []
        total_words = 0

        for section in content_sections:
            heading = section.get("heading", "Section")
            content = section.get("content", "")

            section_text = f"## {heading}\n\n{content}\n\n"
            assembled_sections.append(section_text)

            # Estimate word count
            total_words += len(content.split())

        # Combine into full brief
        full_content = (
            self._brief_template["header"]
            + "".join(assembled_sections)
            + self._brief_template["footer"]
        )

        brief = {
            "brief_id": f"brief_{_trace_id[:8]}",
            "persona_id": persona_id,
            "word_count": total_words,
            "target_word_count": target_word_count,
            "sections": [s.get("heading") for s in content_sections],
            "content": full_content,
            "complete": total_words >= target_word_count * 0.8,
        }

        _log.info(
            "Assembled brief %s for persona %s (%d words)",
            brief["brief_id"],
            persona_id,
            total_words,
        )
        _emit_records_telemetry_event("p4", "brief_assembler", f"assembly_complete:{total_words}")

        return brief

    def get_brief_summary(self, brief: dict[str, Any]) -> dict[str, Any]:
        """Get a summary of a brief for quick reference."""
        return {
            "brief_id": brief.get("brief_id"),
            "persona_id": brief.get("persona_id"),
            "word_count": brief.get("word_count"),
            "complete": brief.get("complete"),
            "sections": brief.get("sections", []),
        }
