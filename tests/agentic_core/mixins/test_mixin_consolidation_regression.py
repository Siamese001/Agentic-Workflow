#!/usr/bin/env python3
"""
Regression tests for mixin consolidation — Phase 2+.

Validates that legacy config compat dataclasses exist and expose
the expected field names with correct defaults.
"""

from __future__ import annotations

import ast
import importlib
from pathlib import Path

# ---------------------------------------------------------------------------
# Module-level import smoke test
# ---------------------------------------------------------------------------


def test_config_compat_can_import():
    """_config_compat module imports without error."""
    mod = importlib.import_module("agentic_core.mixins._config_compat")
    assert mod is not None


# ---------------------------------------------------------------------------
# CacheConfig
# ---------------------------------------------------------------------------


def test_cache_config_fields():
    """CacheConfig exposes legacy field names with correct defaults."""
    from agentic_core.mixins.config_compat_mixin import CacheConfig

    cfg = CacheConfig()
    assert cfg.enabled is True
    assert cfg.max_size == 1000
    assert cfg.default_ttl is None


def test_cache_config_override():
    """CacheConfig fields are overridable."""
    from agentic_core.mixins.config_compat_mixin import CacheConfig

    cfg = CacheConfig(enabled=False, max_size=500, default_ttl=60.0)
    assert cfg.enabled is False
    assert cfg.max_size == 500
    assert cfg.default_ttl == 60.0


