# ---------------------------------------------------------------------------
# AST structural invariant — dataclass-only, no runtime logic
# ---------------------------------------------------------------------------


def test_config_compat_is_dataclass_only():
    """_config_compat.py must contain ONLY dataclass definitions — no functions,
    no method bodies beyond __init__/__repr__/etc. generated by @dataclass."""
    src_path = Path(__file__).resolve().parents[3] / "agentic_core" / "mixins" / "_config_compat.py"
    tree = ast.parse(src_path.read_text(encoding="utf-8"))

    for node in ast.walk(tree):
        # No standalone FunctionDef (methods inside ClassDef are OK — generated by dataclass)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            # Check parent — if inside a ClassDef that's fine (dataclass-generated)
            # Since ast.walk doesn't track parents, we check top-level only
            pass
        # No Call nodes at module level except @dataclass decorator
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            if node.func.id not in ("dataclass",):
                # Allow dataclass() calls only
                pass

    # Ensure exactly 3 ClassDef nodes
    class_defs = [n for n in ast.iter_child_nodes(tree) if isinstance(n, ast.ClassDef)]
    assert len(class_defs) == 3, f"Expected 3 dataclasses, found {len(class_defs)}"

    class_names = {c.name for c in class_defs}
    assert class_names == {"CacheConfig", "MetricsConfig", "BatchingConfig"}

    # Ensure no top-level FunctionDef
    func_defs = [
        n for n in ast.iter_child_nodes(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
    ]
    assert len(func_defs) == 0, f"No top-level functions allowed, found {len(func_defs)}"
