class TestWriteSizeCapError:
    def test_raises_when_content_exceeds_max(self, target):
        oversized = "x" * (MAX_WRITE_BYTES + 1)
        with pytest.raises(WriteSizeCapError) as exc_info:
            write_text(target, oversized)
        assert exc_info.value.proposed_bytes > MAX_WRITE_BYTES
        assert exc_info.value.max_bytes == MAX_WRITE_BYTES
        assert str(target) in str(exc_info.value)

    def test_passes_at_boundary(self, target):
        # Just under cap — must succeed
        content = "x" * (MAX_WRITE_BYTES - 1)
        result = write_text(target, content)
        assert Path(result).exists()

    def test_error_message_contains_path_and_sizes(self, target):
        oversized = "x" * (MAX_WRITE_BYTES + 100)
        with pytest.raises(WriteSizeCapError) as exc_info:
            write_text(target, oversized)
        msg = str(exc_info.value)
        assert "WRITE_SIZE_CAP_EXCEEDED" in msg


