class TestMutationLedger:
    def test_ledger_records_write_text(self, tmp_path, ledger):
        set_mutation_ledger_path(ledger, trace_id="TEST-001")
        target = tmp_path / "out.txt"
        write_text(target, "tracked")

        entries = [json.loads(l) for l in ledger.read_text().splitlines() if l.strip()]
        assert len(entries) >= 1
        last = entries[-1]
        assert last["operation"] == "write_text"
        assert last["result"] == "SUCCESS"
        assert last["trace_id"] == "TEST-001"
        assert last["after_hash"] is not None

    def test_ledger_sequence_increments(self, tmp_path, ledger):
        set_mutation_ledger_path(ledger, trace_id="SEQ")
        write_text(tmp_path / "a.txt", "a")
        write_text(tmp_path / "b.txt", "b")

        entries = [json.loads(l) for l in ledger.read_text().splitlines() if l.strip()]
        seqs = [e["seq"] for e in entries]
        assert seqs == list(range(1, len(seqs) + 1))

    def test_ledger_cleared_on_new_set_mutation_ledger_path(self, tmp_path, ledger):
        set_mutation_ledger_path(ledger, trace_id="RUN1")
        write_text(tmp_path / "x.txt", "x")
        set_mutation_ledger_path(ledger, trace_id="RUN2")  # clears prior
        assert not ledger.exists() or ledger.stat().st_size == 0


