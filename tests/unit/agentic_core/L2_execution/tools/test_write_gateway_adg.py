class TestWriteAmplificationError:
    def test_raises_when_growth_exceeds_ratio(self, target):
        # Write a small file first
        write_text(target, "x" * 100)
        # Now write something 3x larger (exceeds MAX_GROWTH_RATIO=2.0)
        big = "x" * 400
        with pytest.raises(WriteAmplificationError) as exc_info:
            write_text(target, big)
        assert exc_info.value.growth_ratio > MAX_GROWTH_RATIO

    def test_no_raise_on_new_file(self, target):
        # New file — no prior content, growth check skipped
        result = write_text(target, "x" * 1000)
        assert Path(result).exists()

    def test_no_raise_when_growth_within_ratio(self, target):
        write_text(target, "x" * 200)
        # 1.5x growth — within MAX_GROWTH_RATIO=2.0
        result = write_text(target, "x" * 300)
        assert Path(result).exists()

    def test_error_message_contains_ratio(self, target):
        write_text(target, "x" * 100)
        with pytest.raises(WriteAmplificationError) as exc_info:
            write_text(target, "x" * 500)
        assert "WRITE_AMPLIFICATION_DETECTED" in str(exc_info.value)


