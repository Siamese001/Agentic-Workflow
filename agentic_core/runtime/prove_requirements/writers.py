"""
Artifact writers for the requirements proof system.

Writes Phase 0 + Phase 1 artifacts to the configured export directory in
both machine-readable (.json/.csv) and human-readable (.md) form.
"""

from __future__ import annotations

import csv
import json
from collections import Counter
from dataclasses import asdict, is_dataclass
from pathlib import Path
from typing import Dict, List, Sequence

from agentic_core.runtime.prove_requirements.coverage_matrix_builder import (
    CoverageRow,
)
from agentic_core.runtime.prove_requirements.implementation_mapper import (
    ImplementationMapping,
)
from agentic_core.runtime.prove_requirements.types import RequirementRecord


# ---------------------------------------------------------------------------
# Source manifest
# ---------------------------------------------------------------------------

def write_manifest(manifest: Dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "source_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    (out_dir / "source_manifest.md").write_text(
        _manifest_to_md(manifest),
        encoding="utf-8",
    )


def _manifest_to_md(manifest: Dict) -> str:
    s = manifest["summary"]
    lines: List[str] = [
        "# Source Manifest",
        "",
        "Generated by `python -m agentic_core.runtime.prove_requirements`.",
        "",
        f"- generated_at_utc: `{s['generated_at_utc']}`",
        f"- repo_root: `{s['repo_root']}`",
        f"- folder_count_expected: **{s['folder_count_expected']}**",
        f"- folder_count_found: **{s['folder_count_found']}**",
        f"- file_count_ingested: **{s['file_count_ingested']}**",
        f"- missing_folders: `{s['missing_folders']}`",
        f"- empty_folders: `{s['empty_folders']}`",
        f"- excluded_files: `{len(s['excluded_files'])} entries`",
        "",
        "## Files (sorted by relative path)",
        "",
        "| Relative Path | Lines | SHA256 (first 16) |",
        "|---|---:|---|",
    ]
    rows = sorted(manifest["files"], key=lambda r: r["relative_path"])
    for f in rows:
        lines.append(
            f"| `{f['relative_path']}` | {f['line_count']} | `{f['sha256'][:16]}` |"
        )
    lines.append("")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Requirements index
# ---------------------------------------------------------------------------

def write_requirements_index(
    records: Sequence[RequirementRecord],
    out_dir: Path,
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    record_dicts = [_record_to_dict(r) for r in records]
    summary = _index_summary(record_dicts)

    payload = {"summary": summary, "records": record_dicts}
    (out_dir / "requirements_index.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    csv_path = out_dir / "requirements_index.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, quoting=csv.QUOTE_ALL)
        writer.writerow(
            [
                "req_id",
                "source_folder",
                "relative_path",
                "line_start",
                "line_end",
                "owning_layer",
                "requirement_type",
                "status",
                "matched_markers",
                "verification_needed",
                "normalized_requirement",
            ]
        )
        for d in record_dicts:
            writer.writerow(
                [
                    d["req_id"],
                    d["source_folder"],
                    d["relative_path"],
                    d["line_start"],
                    d["line_end"],
                    d["owning_layer"],
                    d["requirement_type"],
                    d["status"],
                    "|".join(d["matched_markers"]),
                    "|".join(d["verification_needed"]),
                    d["normalized_requirement"][:600],
                ]
            )

    (out_dir / "requirements_index.md").write_text(
        _index_to_md(summary),
        encoding="utf-8",
    )


def _record_to_dict(r) -> Dict:
    if is_dataclass(r):
        d = asdict(r)
    elif hasattr(r, "__dict__"):
        d = dict(r.__dict__)
    else:
        d = dict(r)
    for key in ("verification_needed", "matched_markers"):
        if key in d and isinstance(d[key], tuple):
            d[key] = list(d[key])
    return d


def _index_summary(records: List[Dict]) -> Dict:
    by_layer: Counter = Counter()
    by_type: Counter = Counter()
    by_folder: Counter = Counter()
    by_file: Counter = Counter()
    by_status: Counter = Counter()
    for r in records:
        by_layer[r["owning_layer"]] += 1
        by_type[r["requirement_type"]] += 1
        parts = Path(r["relative_path"]).parts
        folder = parts[2] if len(parts) >= 3 else "(unknown)"
        by_folder[folder] += 1
        by_file[r["relative_path"]] += 1
        by_status[r["status"]] += 1
    return {
        "total_requirements": len(records),
        "by_owning_layer": dict(by_layer),
        "by_requirement_type": dict(by_type),
        "by_source_folder": dict(by_folder),
        "by_source_file_top20": dict(by_file.most_common(20)),
        "by_status": dict(by_status),
    }


# ---------------------------------------------------------------------------
# Implementation map (Phase 2)
# ---------------------------------------------------------------------------

def write_implementation_map(
    mappings: Sequence[ImplementationMapping],
    out_dir: Path,
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = [_record_to_dict(m) for m in mappings]
    summary = _impl_map_summary(rows)

    payload = {"summary": summary, "mappings": rows}
    (out_dir / "implementation_map.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    csv_path = out_dir / "implementation_map.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, quoting=csv.QUOTE_ALL)
        writer.writerow(
            [
                "req_id",
                "implementation_status",
                "anchors_extracted",
                "matched_anchors",
                "files",
                "canonical_layer_roots",
                "notes",
            ]
        )
        for d in rows:
            files_str = "|".join(
                f"{f.get('path','')}#{f.get('symbol','')}@L{f.get('line','')}"
                for f in d.get("files", [])
            )
            writer.writerow(
                [
                    d["req_id"],
                    d["implementation_status"],
                    "|".join(d.get("anchors_extracted", [])),
                    "|".join(d.get("matched_anchors", [])),
                    files_str,
                    "|".join(d.get("canonical_layer_roots", [])),
                    (d.get("notes") or "")[:400],
                ]
            )

    # missing_requirements.md -- only req_ids that came out MISSING.
    missing_rows = [d for d in rows if d["implementation_status"] == "MISSING"]
    needs_human = [d for d in rows if d["implementation_status"] == "NEEDS_HUMAN_MAPPING"]
    md_lines = [
        "# Missing Requirements",
        "",
        "Requirements whose anchor symbols did not resolve to any code symbol.",
        "These are candidates for Phase 4 (runtime gap closure) -- if the",
        "requirement is genuine and applicable, code must be written.",
        "",
        f"- total_missing: **{len(missing_rows)}**",
        f"- total_needs_human_mapping: **{len(needs_human)}**",
        "",
        "## MISSING (anchor extracted, no code match)",
        "",
        "| req_id | anchors |",
        "|---|---|",
    ]
    for d in missing_rows[:500]:
        md_lines.append(
            f"| `{d['req_id']}` | `{', '.join(d.get('anchors_extracted', []))[:120]}` |"
        )
    if len(missing_rows) > 500:
        md_lines.append(f"| ... | (+{len(missing_rows) - 500} more in implementation_map.csv) |")
    md_lines += [
        "",
        "## NEEDS_HUMAN_MAPPING (no anchor could be extracted)",
        "",
        "| req_id | source_text excerpt |",
        "|---|---|",
    ]
    for d in needs_human[:200]:
        # Use empty string placeholder; full text is in the JSON record.
        md_lines.append(f"| `{d['req_id']}` | (see requirements_index.json) |")
    if len(needs_human) > 200:
        md_lines.append(f"| ... | (+{len(needs_human) - 200} more in implementation_map.csv) |")
    (out_dir / "missing_requirements.md").write_text(
        "\n".join(md_lines) + "\n", encoding="utf-8"
    )


def _impl_map_summary(rows: List[Dict]) -> Dict:
    by_status: Counter = Counter()
    for r in rows:
        by_status[r["implementation_status"]] += 1
    return {
        "total_mappings": len(rows),
        "by_implementation_status": dict(by_status),
    }


# ---------------------------------------------------------------------------
# Coverage matrix (Phase 3)
# ---------------------------------------------------------------------------

def write_coverage_matrix(
    rows: Sequence[CoverageRow],
    out_dir: Path,
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    row_dicts = [_record_to_dict(r) for r in rows]
    summary = _coverage_summary(row_dicts)

    payload = {"summary": summary, "rows": row_dicts}
    (out_dir / "coverage_matrix.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    csv_path = out_dir / "coverage_matrix.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, quoting=csv.QUOTE_ALL)
        writer.writerow(
            [
                "req_id",
                "relative_path",
                "line_start",
                "line_end",
                "owning_layer",
                "requirement_type",
                "implementation_status",
                "coverage_status",
                "files",
                "test_files",
                "matched_anchors",
                "verification_needed",
                "notes",
                "source_text_excerpt",
            ]
        )
        for d in row_dicts:
            files_str = "|".join(
                f"{f.get('path','')}#{f.get('symbol','')}@L{f.get('line','')}"
                for f in d.get("files", [])
            )
            writer.writerow(
                [
                    d["req_id"],
                    d["relative_path"],
                    d["line_start"],
                    d["line_end"],
                    d["owning_layer"],
                    d["requirement_type"],
                    d["implementation_status"],
                    d["coverage_status"],
                    files_str,
                    "|".join(d.get("test_files", [])),
                    "|".join(d.get("matched_anchors", [])),
                    "|".join(d.get("verification_needed", [])),
                    (d.get("notes") or "")[:400],
                    (d.get("source_text_excerpt") or "")[:400],
                ]
            )

    (out_dir / "coverage_matrix.md").write_text(
        _coverage_to_md(summary), encoding="utf-8"
    )


def _coverage_summary(rows: List[Dict]) -> Dict:
    by_status: Counter = Counter()
    by_layer_status: Counter = Counter()
    by_type_status: Counter = Counter()
    by_layer: Counter = Counter()
    for r in rows:
        by_status[r["coverage_status"]] += 1
        by_layer_status[(r["owning_layer"], r["coverage_status"])] += 1
        by_type_status[(r["requirement_type"], r["coverage_status"])] += 1
        by_layer[r["owning_layer"]] += 1
    return {
        "total_rows": len(rows),
        "by_coverage_status": dict(by_status),
        "by_owning_layer": dict(by_layer),
        "by_layer_status": {f"{k[0]}|{k[1]}": v for k, v in by_layer_status.items()},
        "by_type_status": {f"{k[0]}|{k[1]}": v for k, v in by_type_status.items()},
    }


def _coverage_to_md(summary: Dict) -> str:
    lines: List[str] = [
        "# Coverage Matrix",
        "",
        "Joins requirements_index (Phase 1), implementation_map (Phase 2),",
        "and test_evidence (Phase 3 scan). PROVEN status requires Phase 5",
        "(OTEL), Phase 6 (replay), and Phase 7 (anti-bypass) evidence as",
        "appropriate -- those phases have not run yet, so PROVEN count is",
        "expected to be zero in this build.",
        "",
        f"- total_rows: **{summary['total_rows']}**",
        "",
        "## By Coverage Status",
        "",
        "| Status | Count |",
        "|---|---:|",
    ]
    for k, v in sorted(summary["by_coverage_status"].items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| `{k}` | {v} |")
    lines += ["", "## By Owning Layer x Coverage Status", "", "| Layer | Status | Count |", "|---|---|---:|"]
    for k, v in sorted(summary["by_layer_status"].items(), key=lambda kv: (-kv[1], kv[0])):
        layer, status = k.split("|", 1)
        lines.append(f"| `{layer}` | `{status}` | {v} |")
    return "\n".join(lines) + "\n"


def _index_to_md(summary: Dict) -> str:
    lines: List[str] = [
        "# Requirements Index",
        "",
        "Generated by `python -m agentic_core.runtime.prove_requirements`.",
        "",
        f"- total_requirements: **{summary['total_requirements']}**",
        "",
        "All records start with `status=UNMAPPED`. No record can be marked",
        "PROVEN until Phase 2 (implementation mapping) and Phase 3 (coverage",
        "matrix) are run, and all evidence categories from",
        "`verification_needed` are supplied.",
        "",
        "## By Owning Layer",
        "",
        "| Layer | Count |",
        "|---|---:|",
    ]
    for k, v in sorted(summary["by_owning_layer"].items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| `{k}` | {v} |")
    lines += ["", "## By Requirement Type", "", "| Type | Count |", "|---|---:|"]
    for k, v in sorted(summary["by_requirement_type"].items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| `{k}` | {v} |")
    lines += ["", "## By Source Folder", "", "| Folder | Count |", "|---|---:|"]
    for k, v in sorted(summary["by_source_folder"].items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| `{k}` | {v} |")
    lines += [
        "",
        "## Top 20 Source Files by Requirement Count",
        "",
        "| Relative Path | Count |",
        "|---|---:|",
    ]
    for k, v in summary["by_source_file_top20"].items():
        lines.append(f"| `{k}` | {v} |")
    lines += ["", "## By Status", "", "| Status | Count |", "|---|---:|"]
    for k, v in sorted(summary["by_status"].items()):
        lines.append(f"| `{k}` | {v} |")
    lines += [
        "",
        "## Records",
        "",
        "Per-record fields (req_id, source line range, normalized text, marker tokens, etc.)",
        "live in `requirements_index.json` (canonical) and `requirements_index.csv`",
        "(spreadsheet-friendly). This markdown file is the human-readable summary only.",
    ]
    return "\n".join(lines) + "\n"
