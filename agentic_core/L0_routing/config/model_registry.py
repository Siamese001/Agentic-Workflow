# ============================================================================


def get_model_for_tier(tier: str) -> str:
    """Return the model ID for a given routing tier.

    Args:
        tier: One of ALL_TIERS.

    Returns:
        Model identifier string (or sentinel for DETERMINISTIC / HITL).

    Raises:
        ValueError: If tier is not a known tier.
    """
    mapping: dict[str, str] = {
        TIER_DETERMINISTIC: DETERMINISTIC_MODEL_SENTINEL,
        TIER_QWEN_LOCAL: QWEN_LOCAL_MODEL_ID,
        TIER_GEMINI_FLASH: GEMINI_FLASH_MODEL_ID,
        TIER_GEMINI_PRO: GEMINI_PRO_MODEL_ID,
        TIER_HITL: "human_review",
    }
    if tier not in mapping:
        raise ValueError(f"Unknown tier: {tier!r}. Must be one of {ALL_TIERS}.")
    return mapping[tier]


