"""L6 shadow-evaluation v6 doctrine package (06.x detailed specifications).

This package implements the read-only completed-run evaluation, RCA,
proposal drafting, gauntlet, approval, and future-run activation pipeline
required by:

* ``docs/reference/06_Shadow_Evaluation_System_Learning/06_*_detailed.md``

Top-level entry points:

>>> from agentic_core.L6_observability.shadow_eval import (
...     L6PipelineState, run_6a, run_observer, run_6b, run_6c,
...     run_proposal, run_6d,
... )

The package is intentionally side-effect free at import time. No L4
clients, no UWG clients, no BUS U publishers are imported here. That
absence is part of the proof that the observer law (06.2) is honored.
"""

