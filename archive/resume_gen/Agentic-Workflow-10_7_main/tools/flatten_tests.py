from __future__ import annotations

import argparse
import json
from pathlib import Path
from textwrap import dedent
from typing import Dict, Iterable, List

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = REPO_ROOT / "tests"
OUTPUT_ROOT = REPO_ROOT / "tests_flat"
MANIFEST_PATH = OUTPUT_ROOT / "manifest.json"


def _discover_sources() -> List[Path]:
    paths = [
        path
        for path in SOURCE_ROOT.rglob("*.py")
        if "__pycache__" not in path.parts
    ]
    return sorted(paths, key=lambda p: p.relative_to(SOURCE_ROOT).as_posix())


def _flat_filename(rel_path: Path) -> str:
    if rel_path.name == "conftest.py":
        return "conftest.py"
    stem = rel_path.with_suffix("").as_posix().replace("/", "__")
    return f"test_flat__{stem}.py"


def _quote_literal(text: str) -> str:
    if "\"\"\"" not in text:
        quote = '"""'
    elif "'''" not in text:
        quote = "'''"
    else:
        return repr(text)
    return f"{quote}{text}{quote}"


def _render_file(source_rel: Path) -> str:
    source_text = (SOURCE_ROOT / source_rel).read_text(encoding="utf-8")
    literal = _quote_literal(source_text)

    module_name = ".".join(["tests", *source_rel.with_suffix("").parts])
    flat_module_name = "tests_flat." + source_rel.with_suffix("").as_posix().replace("/", "__")
    source_rel_posix = source_rel.as_posix()

    template = f'''"""Auto-generated flattened view for {source_rel_posix}.

Do not edit this file directly; run tools/flatten_tests.py instead."""
from __future__ import annotations

import sys
import types
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = REPO_ROOT / "tests"
OUTPUT_ROOT = REPO_ROOT / "tests_flat"
SOURCE_REL_PATH = "{source_rel_posix}"
SOURCE_PATH = REPO_ROOT / SOURCE_REL_PATH

# Embedded canonical source
EMBEDDED_SOURCES = {{
    SOURCE_REL_PATH: {literal}
}}

ORIGINAL_MODULE_NAME = "{module_name}"
FLAT_MODULE_NAME = "{flat_module_name}"


def _ensure_import_roots() -> None:
    root = str(REPO_ROOT)
    flat_root = str(OUTPUT_ROOT)
    for candidate in (root, flat_root):
        if candidate not in sys.path:
            sys.path.insert(0, candidate)
    tests_pkg = sys.modules.setdefault("tests", types.ModuleType("tests"))
    tests_pkg.__path__ = list({{*(getattr(tests_pkg, "__path__", []) or []), str(SOURCE_ROOT), flat_root}})
    tests_flat_pkg = sys.modules.setdefault("tests_flat", types.ModuleType("tests_flat"))
    tests_flat_pkg.__path__ = list({{*(getattr(tests_flat_pkg, "__path__", []) or []), flat_root}})


def _materialize_module() -> types.ModuleType:
    module = types.ModuleType(ORIGINAL_MODULE_NAME)
    module.__file__ = str(SOURCE_PATH)
    module.__package__ = ORIGINAL_MODULE_NAME.rpartition(".")[0]
    exec(compile(EMBEDDED_SOURCES[SOURCE_REL_PATH], str(SOURCE_PATH), "exec"), module.__dict__)
    sys.modules[ORIGINAL_MODULE_NAME] = module
    sys.modules[FLAT_MODULE_NAME] = module
    return module


_ensure_import_roots()
_embedded_module = _materialize_module()
for _name, _value in list(_embedded_module.__dict__.items()):
    if _name == "__builtins__":
        continue
    globals()[_name] = _value
'''
    return dedent(template)


def _write_file(target: Path, content: str) -> None:
    target.write_text(content, encoding="utf-8")


def _clean_existing() -> None:
    for path in OUTPUT_ROOT.glob("*.py"):
        if path.name == "__init__.py":
            continue
        path.unlink()


def _generate_files(sources: Iterable[Path]) -> List[Dict[str, str]]:
    manifest: List[Dict[str, str]] = []
    for source in sources:
        rel = source.relative_to(SOURCE_ROOT)
        flat_name = _flat_filename(rel)
        flat_path = OUTPUT_ROOT / flat_name
        content = _render_file(rel)
        _write_file(flat_path, content)
        manifest.append({"source": f"tests/{rel.as_posix()}", "flat": f"tests_flat/{flat_name}"})
    return manifest


def _ensure_init_file() -> None:
    init_path = OUTPUT_ROOT / "__init__.py"
    if init_path.exists():
        return
    init_path.write_text("\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Regenerate flattened test mirror")
    parser.add_argument("--manifest", default=str(MANIFEST_PATH), help="Output manifest path")
    args = parser.parse_args()

    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    _ensure_init_file()
    _clean_existing()

    sources = _discover_sources()
    manifest = _generate_files(sources)

    manifest_path = Path(args.manifest)
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"Wrote {len(manifest)} flattened modules to {OUTPUT_ROOT}")


if __name__ == "__main__":
    main()
