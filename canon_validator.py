            rel = f.relative_to(ROOT)
            if any(p in {"__pycache__", ".git", "node_modules"} for p in rel.parts):
                continue
            lower_name = f.name.lower()
            # Split by underscores and dots for discrete word matching
            name_parts = set(re.split(r'[_.]', lower_name))
