"""ADG R6 Backlog Enricher — 5 remaining low-effort detectors.

Sibling to debt_overlay_enricher (R1-R4) and truth_expansion_enricher (R5).
Implements the remaining low-effort detectors from the R5 backlog.

Detectors:

  A13  async_fire_and_forget
       `asyncio.create_task(...)` / `loop.create_task(...)` whose return
       value is discarded (not assigned, awaited, or stored)
  A14  external_call_no_timeout
       requests.X() / httpx.X() / aiohttp.X() without `timeout=` kwarg
  A15  snapshot_metadata
       Record git SHA, dirty status, generation time, newest indexed
       file mtime — so downstream tools can detect stale snapshots
  A16  boundary_strings_unresolved
       String literals in .py code that LOOK like module paths
       ("agentic_core.foo.Bar") but don't resolve on disk
  A17  rename_shim_consumer_risk (view-only; joins existing shim data)
       WHO still imports the rename shims? (join shim modules × fan-in)
  A19  mcp_tool_contract_drift
       Compare .cursor/mcp.json servers vs tools/*/mcp_*_server.py
       @tool declarations

Bonus:
  A18  source_origin tagging
       handwritten (default) | generated | vendored | archived
       Feeds into severity calibration — generated code should not raise
       violations as loudly as handwritten code.

All findings land in sibling tables + `overlay_violations`.
Canonical tables untouched.

Entry point: `enrich_r6(sqlite_path: Path) -> dict[str, int]`
"""

