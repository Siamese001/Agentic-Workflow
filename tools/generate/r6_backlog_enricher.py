# A14 — libraries whose HTTP calls require `timeout=`
HTTP_LIBS_STRICT: set[str] = {"requests", "httpx", "aiohttp"}
HTTP_METHODS: set[str] = {"get", "post", "put", "patch", "delete", "head", "options", "request"}

# A13 — task creation patterns (function names that create async tasks)
ASYNC_TASK_CREATORS: set[str] = {
    "create_task",
    "ensure_future",
    "async_task",
}

# A16 — boundary string heuristic: look for module-looking dotted names
BOUNDARY_STRING_RE = re.compile(
    r"^(?:apps_rg|apps_shared|apps_underwriting_ai|system_learning|tools|"
    r"ops_scripts|infrastructure)"
    r"(?:\.[A-Za-z_][A-Za-z0-9_]*){2,}$"
)

# A18 — generated-code markers
GENERATED_HEADER_RE = re.compile(
    r"(?:# *)?(?:@generated|DO NOT EDIT|auto-generated|automatically generated|"
    r"generated by [\w\s]+)",
    re.IGNORECASE,
)
VENDOR_PATH_PREFIXES = ("vendor/", "third_party/", "_vendor/")


# ----------------------------------------------------------- progress reporter
class _Progress:
    def __init__(self, total: int, label: str) -> None:
        self.total = max(total, 1)
        self.n = 0
        self.label = label
        self.t0 = time.time()
        self.last = 0.0

    def tick(self, by: int = 1) -> None:
        self.n += by
        now = time.time()
        if now - self.last < 1.0 and self.n < self.total:
            return
        self.last = now
        pct = 100 * self.n / self.total
        fill = int(pct * 40 / 100)
        bar = "\u2588" * fill + "\u2591" * (40 - fill)
        elapsed = now - self.t0
        eta = (elapsed / max(self.n, 1)) * (self.total - self.n)
        if pct >= 90:
            color = "\033[92m"
        elif pct >= 70:
            color = "\033[94m"
        elif pct >= 40:
            color = "\033[93m"
        else:
            color = "\033[91m"
        sys.stderr.write(
            f"\r{color}[{bar}]\033[0m {pct:5.1f}% ({self.n}/{self.total}) - ETA: {eta:5.0f}s - {self.label}"
        )
        sys.stderr.flush()

    def done(self) -> None:
        sys.stderr.write(
            f"\r\033[92m[{'\u2588' * 40}]\033[0m 100.0% ({self.total}/{self.total}) - {self.label} done\n"
        )


# ---------------------------------------------------- file walking
def _iter_py_files() -> list[Path]:
    out: list[Path] = []
    for py in ROOT.rglob("*.py"):
        rel_parts = py.relative_to(ROOT).parts
        if set(rel_parts) & EXCLUDE_DIRS:
            continue
        out.append(py)
    return out


def _safe_read(p: Path) -> str | None:
    try:
        return p.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _safe_parse(txt: str) -> ast.Module | None:
    try:
        return ast.parse(txt)
    except SyntaxError:
        return None


# ---------------------------------------------------- A13 + A14 + A16 visitor
class _R6Visitor(ast.NodeVisitor):
    """Single-pass collector for A13, A14, A16."""

    def __init__(self) -> None:
        self.async_fire_and_forget: list[dict] = []
        self.timeout_gaps: list[dict] = []
        self.boundary_strings: list[dict] = []

    # A13 — create_task whose result is discarded
    # We recognize discarded-return by parent context: `ast.Expr(value=Call)`.
    # Traverse via generic_visit and check parent in visit_Expr.
    def visit_Expr(self, node: ast.Expr) -> None:
        if isinstance(node.value, ast.Call):
            self._maybe_record_fire_forget(node.value, is_discarded=True)
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        self._maybe_record_fire_forget(node, is_discarded=False)
        self._maybe_record_timeout_gap(node)
        self.generic_visit(node)

    def _maybe_record_fire_forget(self, call: ast.Call, *, is_discarded: bool) -> None:
        fn = call.func
        # Resolve attribute form: module.create_task(...)
        name = None
        mod = None
        if isinstance(fn, ast.Attribute):
            name = fn.attr
            if isinstance(fn.value, ast.Name):
                mod = fn.value.id
        elif isinstance(fn, ast.Name):
            name = fn.id
        if name not in ASYNC_TASK_CREATORS:
            return
        # Heuristic: asyncio.create_task or loop.create_task — require
        # asyncio/loop context OR bare `create_task` import.
        acceptable_mods = {"asyncio", "loop", "_loop", "self"}
        if mod is not None and mod not in acceptable_mods and mod != "None":
            # Unlikely to be asyncio — skip
            return
        # Record only if discarded (called in Expr statement context)
        if is_discarded:
            self.async_fire_and_forget.append(
                {
                    "line": call.lineno,
                    "callee": f"{mod or ''}.{name}".lstrip("."),
                }
            )

    def _maybe_record_timeout_gap(self, call: ast.Call) -> None:
        fn = call.func
        if not isinstance(fn, ast.Attribute):
            return
        if not isinstance(fn.value, ast.Name):
            return
        lib = fn.value.id
        method = fn.attr
        if lib not in HTTP_LIBS_STRICT:
            return
        if method not in HTTP_METHODS:
            return
        # Check for timeout= kwarg
        has_timeout = any(kw.arg == "timeout" for kw in call.keywords)
        if not has_timeout:
            self.timeout_gaps.append(
                {
                    "line": call.lineno,
                    "lib": lib,
                    "method": method,
                }
            )

    # A16 — boundary strings (module-looking dotted names in string literals)
    def visit_Constant(self, node: ast.Constant) -> None:
        if not isinstance(node.value, str):
            return
        v = node.value.strip()
        if len(v) < 10 or len(v) > 120:
            return
        m = BOUNDARY_STRING_RE.match(v)
        if not m:
            return
        self.boundary_strings.append(
            {
                "line": node.lineno,
                "target": v,
            }
        )


# ---------------------------------------------------- A16 resolution helper
def _resolve_module_path(target: str) -> bool:
    as_path = target.replace(".", "/")
    py_file = ROOT / f"{as_path}.py"
    pkg_init = ROOT / as_path / "__init__.py"
    pkg_dir = ROOT / as_path
    return py_file.exists() or pkg_init.exists() or pkg_dir.is_dir()


# ---------------------------------------------------- A18 source origin
def _source_origin(rel: str, txt: str) -> str:
    if any(p in rel for p in VENDOR_PATH_PREFIXES):
        return "vendored"
    if "archives/" in rel or "tools_graveyard" in rel:
        return "archived"
    # Check first ~20 lines for generated header
    head = "\n".join(txt.splitlines()[:20])
    if GENERATED_HEADER_RE.search(head):
        return "generated"
    return "handwritten"


# ---------------------------------------------------- A15 snapshot freshness
def _collect_snapshot_metadata() -> dict[str, str]:
    meta: dict[str, str] = {}
    # Git SHA
    try:
        sha = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
        meta["git_head_sha"] = sha.stdout.strip() or "unknown"
    except (OSError, subprocess.SubprocessError):
        meta["git_head_sha"] = "unavailable"
    # Dirty status
    try:
        st = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
        meta["git_dirty"] = "1" if st.stdout.strip() else "0"
        meta["git_dirty_files"] = str(len(st.stdout.strip().splitlines()))
    except (OSError, subprocess.SubprocessError):
        meta["git_dirty"] = "unknown"
        meta["git_dirty_files"] = "0"
    # Branch
    try:
        br = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
        meta["git_branch"] = br.stdout.strip() or "unknown"
    except (OSError, subprocess.SubprocessError):
        meta["git_branch"] = "unavailable"
    # Timestamp
    meta["generated_at_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    meta["generated_at_epoch"] = str(int(time.time()))
    return meta


# ---------------------------------------------------- A19 MCP contract drift
MCP_TOOL_DECORATOR_RE = re.compile(r"@(?:mcp\.)?tool\b")
MCP_CONFIG_PATH = ROOT / "docs/archive/windsurf/legacy-tree" / "mcp_config.json"


def _collect_mcp_declarations() -> list[dict]:
    """Find @tool / @mcp.tool / @app.tool decorated functions across tools/.

    Returns [{file, tool_name, decorator}].
    """
    decls: list[dict] = []
    # Broad search across tools/ — narrower filtering happens at decorator level
    search_roots = [ROOT / "tools"]
    mcp_files: set[Path] = set()
    for root in search_roots:
        if not root.is_dir():
            continue
        for py in root.rglob("*.py"):
            rel_parts = py.relative_to(ROOT).parts
            if set(rel_parts) & EXCLUDE_DIRS:
                continue
            mcp_files.add(py)

    for py in sorted(mcp_files):
        rel = str(py.relative_to(ROOT)).replace("\\", "/")
        txt = _safe_read(py)
        if txt is None:
            continue
        tree = _safe_parse(txt)
        if tree is None:
            continue
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                for deco in node.decorator_list:
                    deco_src = ast.unparse(deco) if sys.version_info >= (3, 9) else ""
                    deco_l = deco_src.lower()
                    # Match @tool, @mcp.tool, @app.tool, @server.tool
                    is_tool_deco = (
                        deco_l == "tool"
                        or deco_l.startswith("tool(")
                        or ".tool" in deco_l
                        or "@mcp" in f"@{deco_l}"
                    )
                    if is_tool_deco:
                        decls.append(
                            {
                                "file": rel,
                                "tool_name": node.name,
                                "decorator": deco_src[:120],
                            }
                        )
                        break
    return decls


def _normalize_arg_path(args: list) -> str | None:
    """Extract the python script path from MCP args, normalize to repo-relative.

    Examples:
      ["-u", "-m", "tools.adg.mcp.server"] -> "tools/adg/mcp/server.py"
      ["-u", "${env:AGENTIC_REPO_ROOT}/tools/mcp/redis_mcp_server.py"]
        -> "tools/mcp/redis_mcp_server.py"
    """
    for i, arg in enumerate(args):
        s = str(arg)
        # `-m module.path`
        if s == "-m" and i + 1 < len(args):
            modpath = str(args[i + 1]).strip()
            return modpath.replace(".", "/") + ".py"
        # path-like
        if s.endswith(".py"):
            # Strip env var prefix
            if "tools/" in s:
                return s[s.index("tools/") :].replace("\\", "/")
            if "tools\\" in s:
                return s[s.index("tools\\") :].replace("\\", "/")
    return None


def _collect_mcp_config_servers() -> list[dict]:
    """Return list of MCP servers from mcp_config.json.

    Each entry includes `is_internal` — True if the command runs a local
    Python module (and we therefore expect a matching @tool file in-repo),
    False if it's an external package (npx/uvx/docker — no local file
    expected).
    """
    if not MCP_CONFIG_PATH.exists():
        return []
    try:
        data = json.loads(MCP_CONFIG_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return []
    servers = []
    for name, cfg in (data.get("mcpServers") or {}).items():
        cmd = (cfg.get("command") or "").lower()
        args = cfg.get("args") or []
        # Internal = python/python.exe + a script path, OR cmd contains
        # tools/ already.
        is_internal = (
            "python" in cmd
            or "py " in cmd
            or any("tools/" in str(a) or "tools\\" in str(a) or str(a).endswith(".py") for a in args)
        )
        script_path = _normalize_arg_path(args) if is_internal else None
        # If script ends in .py but the file doesn't exist on disk, also
        # check the `.py` from a `-m` module path
        if script_path:
            disk = ROOT / script_path
            if not disk.exists():
                # Try as package: script.replace('.py','/__init__.py')
                pkg_init = ROOT / script_path.replace(".py", "/__init__.py")
                if pkg_init.exists():
                    script_path = str(pkg_init.relative_to(ROOT)).replace("\\", "/")
        # Compute script_dir for sibling-tool matching
        script_dir = ""
        if script_path:
            parts = script_path.rsplit("/", 1)
            script_dir = parts[0] if len(parts) > 1 else ""
        servers.append(
            {
                "name": name,
                "args": args,
                "disabled": cfg.get("disabled", False),
                "is_internal": is_internal,
                "script_path": script_path or "",
                "script_dir": script_dir,
            }
        )
    return servers


