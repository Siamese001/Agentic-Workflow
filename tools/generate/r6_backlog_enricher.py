def _ensure_schema(con: sqlite3.Connection) -> None:
    cur = con.cursor()
    # Idempotent migration: drop tables that may have evolved schema since
    # the last enrichment run. CREATE IF NOT EXISTS won't update them.
    for legacy in ("mcp_config_servers",):
        try:
            cur.execute(f"DROP TABLE IF EXISTS {legacy}")
        except sqlite3.Error:
            pass
    # overlay_violations may not exist if running standalone
    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS overlay_violations (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            category        TEXT NOT NULL,
            severity        TEXT NOT NULL DEFAULT 'MEDIUM',
            file_path       TEXT NOT NULL DEFAULT '',
            line_no         INTEGER,
            evidence        TEXT NOT NULL DEFAULT '',
            violation_class TEXT NOT NULL DEFAULT 'overlay_enrichment',
            disposition     TEXT NOT NULL DEFAULT 'untriaged'
        )
        """
    )
    for stmt in SCHEMA_STATEMENTS:
        cur.execute(stmt)
    for stmt in INDEX_STATEMENTS:
        cur.execute(stmt)
    con.commit()


def _ensure_views(con: sqlite3.Connection) -> None:
    cur = con.cursor()
    for name in (
        "mv_async_fire_and_forget_hotspots",
        "mv_external_calls_no_timeout",
        "mv_boundary_string_unresolved",
        "mv_mcp_contract_drift",
        "mv_rename_shim_consumers",
        "mv_r6_summary",
    ):
        cur.execute(f"DROP VIEW IF EXISTS {name}")
    for stmt in VIEW_STATEMENTS:
        cur.execute(stmt)
    con.commit()


# ---------------------------------------------------- main entrypoint
def enrich_r6(sqlite_path: Path) -> dict[str, int]:
    if not sqlite_path.exists():
        raise FileNotFoundError(sqlite_path)

    con = sqlite3.connect(str(sqlite_path))
    try:
        _ensure_schema(con)
        cur = con.cursor()

        # --- Pass 1: Python files for A13/A14/A16/A18
        py_files = _iter_py_files()
        pr = _Progress(len(py_files), label="r6-backlog (.py pass)")
        aff_rows: list[tuple[str, int, str]] = []
        ec_rows: list[tuple[str, int, str, str, int]] = []
        bs_rows: list[tuple[str, int, str, int]] = []
        origin_rows: list[tuple[str, str]] = []
        v_rows: list[tuple] = []

        for py in py_files:
            rel = str(py.relative_to(ROOT)).replace("\\", "/")
            txt = _safe_read(py)
            if txt is None:
                pr.tick()
                continue
            # A18 source origin
            origin = _source_origin(rel, txt)
            origin_rows.append((rel, origin))
            tree = _safe_parse(txt)
            pr.tick()
            if tree is None:
                continue
            v = _R6Visitor()
            v.visit(tree)
            # A13
            for a in v.async_fire_and_forget:
                aff_rows.append((rel, a["line"], a["callee"]))
                v_rows.append(
                    (
                        "async_fire_and_forget",
                        "MEDIUM",
                        rel,
                        a["line"],
                        f"{a['callee']}() return value discarded — exceptions will be lost",
                        "overlay_enrichment",
                    )
                )
            # A14
            # First gather all HTTP-lib calls to derive the has_timeout stat
            # (visitor only records the NO-timeout gaps). For full external_calls
            # table, we'd need both. Keeping minimal: store no-timeout as gaps.
            for g in v.timeout_gaps:
                ec_rows.append((rel, g["line"], g["lib"], g["method"], 0))
                v_rows.append(
                    (
                        "external_call_no_timeout",
                        "MEDIUM",
                        rel,
                        g["line"],
                        f"{g['lib']}.{g['method']}(...) without timeout=",
                        "overlay_enrichment",
                    )
                )
            # A16
            for bs in v.boundary_strings:
                resolved = _resolve_module_path(bs["target"])
                bs_rows.append(
                    (
                        rel,
                        bs["line"],
                        bs["target"],
                        1 if resolved else 0,
                    )
                )
                if not resolved:
                    v_rows.append(
                        (
                            "boundary_string_unresolved",
                            "LOW",
                            rel,
                            bs["line"],
                            f'"{bs["target"]}" — string looks like a module path '
                            "but does not resolve on disk",
                            "overlay_enrichment",
                        )
                    )
        pr.done()

        # --- Pass 2: A15 snapshot metadata
        print("# r6: collecting snapshot metadata", file=sys.stderr)
        meta = _collect_snapshot_metadata()

        # --- Pass 3: A19 MCP contract
        print("# r6: collecting MCP declarations", file=sys.stderr)
        mcp_decls = _collect_mcp_declarations()
        mcp_servers = _collect_mcp_config_servers()

        # --- Write all rows
        cur.execute("DELETE FROM async_fire_and_forget")
        cur.executemany(
            "INSERT INTO async_fire_and_forget (file_path, line_no, callee) VALUES (?, ?, ?)",
            aff_rows,
        )
        cur.execute("DELETE FROM external_calls")
        cur.executemany(
            "INSERT INTO external_calls "
            "(file_path, line_no, lib, method, has_timeout) "
            "VALUES (?, ?, ?, ?, ?)",
            ec_rows,
        )
        cur.execute("DELETE FROM boundary_strings")
        cur.executemany(
            "INSERT INTO boundary_strings (file_path, line_no, target, resolved) VALUES (?, ?, ?, ?)",
            bs_rows,
        )
        cur.execute("DELETE FROM module_origins")
        cur.executemany(
            "INSERT OR REPLACE INTO module_origins (file_path, origin) VALUES (?, ?)",
            origin_rows,
        )
        cur.execute("DELETE FROM snapshot_metadata")
        cur.executemany(
            "INSERT OR REPLACE INTO snapshot_metadata (key, value) VALUES (?, ?)",
            list(meta.items()),
        )
        cur.execute("DELETE FROM mcp_tool_declarations")
        cur.executemany(
            "INSERT INTO mcp_tool_declarations (file_path, tool_name, decorator) VALUES (?, ?, ?)",
            [(d["file"], d["tool_name"], d["decorator"]) for d in mcp_decls],
        )
        cur.execute("DELETE FROM mcp_config_servers")
        cur.executemany(
            "INSERT INTO mcp_config_servers "
            "(name, disabled, is_internal, script_path, script_dir, args) "
            "VALUES (?, ?, ?, ?, ?, ?)",
            [
                (
                    s["name"],
                    1 if s["disabled"] else 0,
                    1 if s.get("is_internal") else 0,
                    s.get("script_path", ""),
                    s.get("script_dir", ""),
                    json.dumps(s["args"]),
                )
                for s in mcp_servers
            ],
        )

        # A17/A19 — violations derived from view results
        # Delete prior R6 overlay rows before inserting fresh
        cur.execute(
            """
            DELETE FROM overlay_violations
            WHERE category IN (
                'async_fire_and_forget', 'external_call_no_timeout',
                'boundary_string_unresolved', 'snapshot_dirty',
                'mcp_contract_drift', 'rename_shim_consumer_risk'
            )
            """
        )
        cur.executemany(
            "INSERT INTO overlay_violations "
            "(category, severity, file_path, line_no, evidence, "
            "violation_class) VALUES (?, ?, ?, ?, ?, ?)",
            v_rows,
        )
        # A15: snapshot_dirty as ADVISORY (not an error — just signal)
        if meta.get("git_dirty") == "1":
            cur.execute(
                "INSERT INTO overlay_violations "
                "(category, severity, file_path, line_no, evidence, "
                "violation_class) VALUES (?, ?, ?, ?, ?, ?)",
                (
                    "snapshot_dirty",
                    "ADVISORY",
                    "",
                    None,
                    f"working tree is dirty at generation "
                    f"({meta.get('git_dirty_files', '?')} files) — snapshot "
                    "reflects uncommitted state",
                    "overlay_enrichment",
                ),
            )
        con.commit()
        _ensure_views(con)

        # A19 drift — materialize view rows into overlay_violations
        drift_rows = cur.execute(
            "SELECT drift_kind, server_or_tool, note FROM mv_mcp_contract_drift"
        ).fetchall()
        for drift_kind, target, note in drift_rows:
            severity = "MEDIUM" if drift_kind == "orphan_server" else "LOW"
            cur.execute(
                "INSERT INTO overlay_violations "
                "(category, severity, file_path, line_no, evidence, "
                "violation_class) VALUES (?, ?, ?, ?, ?, ?)",
                (
                    "mcp_contract_drift",
                    severity,
                    target,
                    None,
                    f"[{drift_kind}] {note}",
                    "overlay_enrichment",
                ),
            )

        # A17 — rename_shim_consumer_risk: any shim with fan-in > 0
        shim_consumer_rows = cur.execute(
            "SELECT shim_file, import_fanin FROM mv_rename_shim_consumers WHERE import_fanin > 0"
        ).fetchall()
        for shim_file, fanin in shim_consumer_rows:
            cur.execute(
                "INSERT INTO overlay_violations "
                "(category, severity, file_path, line_no, evidence, "
                "violation_class) VALUES (?, ?, ?, ?, ?, ?)",
                (
                    "rename_shim_consumer_risk",
                    "MEDIUM",
                    shim_file,
                    None,
                    f"shim has {fanin} import(s) — cannot delete until consumers migrate",
                    "overlay_enrichment",
                ),
            )
        con.commit()

        # --- Summary
        summary: dict[str, int] = {
            "async_fire_and_forget": len(aff_rows),
            "external_calls_no_timeout": len(ec_rows),
            "boundary_strings_total": len(bs_rows),
            "boundary_strings_unresolved": sum(1 for r in bs_rows if r[3] == 0),
            "module_origins_recorded": len(origin_rows),
            "generated_modules": sum(1 for r in origin_rows if r[1] == "generated"),
            "vendored_modules": sum(1 for r in origin_rows if r[1] == "vendored"),
            "archived_modules": sum(1 for r in origin_rows if r[1] == "archived"),
            "mcp_tool_declarations": len(mcp_decls),
            "mcp_config_servers": len(mcp_servers),
            "mcp_contract_drift": len(drift_rows),
            "rename_shim_consumer_risk": len(shim_consumer_rows),
            "snapshot_dirty": 1 if meta.get("git_dirty") == "1" else 0,
        }
        summary["git_head_sha"] = meta.get("git_head_sha", "")  # type: ignore[assignment]
        summary["generated_at_utc"] = meta.get("generated_at_utc", "")  # type: ignore[assignment]
        return summary
    finally:
        con.close()


# ----------------------------------------------------------- CLI
def main() -> int:
    import argparse
    import glob

    parser = argparse.ArgumentParser()
    parser.add_argument("--sqlite")
    args = parser.parse_args()

    if args.sqlite:
        path = Path(args.sqlite)
    else:
        snaps = sorted(
            glob.glob(str(ROOT / "artifacts/adg/adg_indexed_*.sqlite")),
            key=os.path.getmtime,
        )
        if not snaps:
            tmps = sorted(
                glob.glob(str(ROOT / "artifacts/adg/adg_indexed_*.sqlite.tmp")),
                key=os.path.getmtime,
            )
            if not tmps:
                print("FATAL: no snapshot", file=sys.stderr)
                return 2
            path = Path(tmps[-1])
        else:
            path = Path(snaps[-1])

    print(f"# r6 enrichment: {path.name}", file=sys.stderr)
    summary = enrich_r6(path)
    print(json.dumps(summary, indent=2, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(main())
