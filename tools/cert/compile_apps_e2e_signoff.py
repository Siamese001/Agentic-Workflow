"""W3 of plan apps-fort-knox-parity-c5d9a3 \u2014 Apps_e2e Fort Knox Sign-off Compiler.

HOSTILE VERIFIER. Distrusts:
  * the W2 emitter's summary line
  * cached reports
  * previous statuses
  * its own prior output
  * any assertion not produced by an allowlisted command

The ONLY authoritative inputs are:
  data/certification/apps_e2e_requirements_source.json    (what must be proven)
  data/certification/apps_evidence_assertions.jsonl       (atomic proof assertions)
  referenced on-disk artifacts                       (re-opened, re-hashed every run)

A requirement is SIGNED_OFF only when every required control has at least
one valid PASS assertion that:
  - is schema-valid
  - is deterministically identified
  - carries exact req_id, exact control, row_specific=true
  - references an artifact that exists on disk with matching sha256
  - references a pointer that resolves inside the artifact
  - proves row-specificity per apps_e2e's app-keyed semantics (see below)
  - was generated by a command on the row's allowed_verifier_commands list
  - uses an artifact_class on the row's allowed_artifact_classes list
  - was generated within the row's freshness_hours window

Row-specificity for apps_e2e (diverges from agentic_core):
  The authoritative verifier artifact (verifier_report.json) is keyed by
  app_name, not by req_id. Claiming "the artifact contains the req_id"
  would be a lie. Instead:
    - canary (APPS-REQ-001, compiler-self-emitted): req_id literal in the
      catalog artifact is the proof;
    - matrix-governance (APPS-REQ-033): the matrix IS the authoritative
      artifact for matrix_integrity; pointer resolution on the matrix
      is the proof;
    - per-app rows (owner_app set): assertion.app_name == row.owner_app
      AND the pointer-resolved payload contains the app_name is the proof;
    - cross-cutting rows iterating over certified apps: assertion.app_name
      is set and the pointer-resolved payload contains that app_name.

Positive-control canary (APPS-REQ-001):
  The compiler SELF-EMITS a PASS assertion for (APPS-REQ-001,
  catalog_self_consistency) iff every catalog invariant holds
  (schema-valid, no duplicate req_ids, every depends_on resolves, exactly
  one is_positive_control=true). Any catalog-invariant failure prevents
  emission, which flips the canary to BLOCKED, which fails the run.

Trust levels (in ascending order):
  FAILED                       \u2014 compiler crashed or report schema-invalid
  DEVELOPMENT_PROOF            \u2014 one or more non-waiver rows still open
  INTEGRITY_PROOF              \u2014 every non-waiver row SIGNED_OFF, Merkle verified, no signature yet
  SIGNED_OFF_WITH_WAIVERS      \u2014 same as INTEGRITY_PROOF plus at least one active waiver row (expected steady state while apps_qna + apps_underwriting_ai remain waivers)
  SIGNED_PROOF                 \u2014 signature verified (W5 will upgrade this)
  FINAL_SIGNED_CERTIFICATION   \u2014 external trust authority (out of repo scope)

Outputs (all under artifacts/certification/apps_e2e/):
  apps_e2e_signoff_report.json
  apps_e2e_signoff_report.sha256
  apps_e2e_signoff_report.merkle.json
"""
