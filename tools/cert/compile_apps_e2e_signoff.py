class CompileError(Exception):
    pass


def check_catalog_self_consistency(catalog: dict[str, Any]) -> list[str]:
    """Return a list of catalog-invariant violations. Empty list == canary PASS.

    The compiler will emit a PASS assertion for APPS-REQ-001 iff this returns [].
    """
    violations: list[str] = []
    reqs = catalog.get("requirements", [])
    # 1. No duplicate req_ids.
    ids = [r["req_id"] for r in reqs]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        violations.append(f"duplicate req_ids: {sorted(dupes)}")
    # 2. Every depends_on resolves.
    known = set(ids)
    for r in reqs:
        for dep in r.get("depends_on_req_ids", []):
            if dep not in known:
                violations.append(f"{r['req_id']} depends on unknown {dep}")
    # 3. No self-dependency.
    for r in reqs:
        if r["req_id"] in r.get("depends_on_req_ids", []):
            violations.append(f"{r['req_id']} depends on itself")
    # 4. Exactly one is_positive_control=true row.
    canaries = [r for r in reqs if r.get("is_positive_control")]
    if len(canaries) != 1:
        violations.append(
            f"expected exactly 1 positive_control row; got {len(canaries)}"
        )
    elif canaries[0]["req_id"] != catalog.get("positive_control_req_id"):
        violations.append(
            f"positive_control_req_id header mismatch: "
            f"header={catalog.get('positive_control_req_id')!r}, "
            f"row={canaries[0]['req_id']!r}"
        )
    # 5. requirement_count lockstep check (W1.P1 of apps-fortknox-evidence-repackage)
    declared_count = catalog.get("requirement_count")
    actual_count = len(reqs)
    if declared_count != actual_count:
        violations.append(
            f"requirement_count mismatch: declared={declared_count}, "
            f"actual={actual_count} (len(requirements))"
        )
    return violations


# =============================================================================
# Row-specificity guard (app-keyed semantics)
# =============================================================================

def _row_specificity_ok(
    assertion: dict[str, Any],
    req: dict[str, Any],
    parsed_artifact: Any,
) -> tuple[bool, str]:
    """Enforce apps_e2e's app-keyed row-specificity guard.

    Returns (ok, reason). See module docstring for the four rules.
    """
    req_id = req["req_id"]
    claim_type = req["claim_type"]
    owner_app = req.get("owner_app")
    pointer = assertion["artifact_payload_pointer"]
    app_name = assertion.get("app_name")

    # Canary: req_id literal in the catalog artifact.
    if claim_type == "APPS_POSITIVE_CONTROL":
        # Compiler-self-emitted; accept unconditionally if we got this far.
        # Row_specificity is proven by the catalog-self-consistency check.
        return (True, "")

    # Matrix governance: pointer resolved is the matrix root.
    if claim_type == "APPS_MATRIX_GOVERNANCE":
        if parsed_artifact is None:
            return (False, "matrix artifact not JSON-parseable")
        val = resolve_json_pointer(parsed_artifact, pointer)
        if isinstance(val, _MissingSentinel):
            return (False, f"pointer {pointer!r} did not resolve in matrix")
        return (True, "")

    # Per-app rows (owner_app set).
    if owner_app is not None:
        if app_name != owner_app:
            return (False, f"assertion.app_name={app_name!r} does not match row.owner_app={owner_app!r}")
        if parsed_artifact is not None:
            val = resolve_json_pointer(parsed_artifact, pointer)
            if isinstance(val, _MissingSentinel):
                return (False, f"pointer {pointer!r} did not resolve")
            snippet = json.dumps(val, sort_keys=True) if not isinstance(val, str) else val
            if owner_app not in snippet:
                return (False, f"app_name {owner_app!r} not in payload at {pointer!r}")
        return (True, "")

    # Cross-cutting over certified apps.
    if app_name is None:
        return (False, f"cross-cutting row {req_id} requires assertion.app_name to be set")
    if parsed_artifact is not None:
        val = resolve_json_pointer(parsed_artifact, pointer)
        if isinstance(val, _MissingSentinel):
            return (False, f"pointer {pointer!r} did not resolve")
        snippet = json.dumps(val, sort_keys=True) if not isinstance(val, str) else val
        if app_name not in snippet:
            return (False, f"app_name {app_name!r} not in payload at {pointer!r}")
    return (True, "")


# =============================================================================
# Assertion validator
# =============================================================================

def validate_assertion(
    assertion: dict[str, Any],
    req: dict[str, Any],
    artifact_cache: dict[str, tuple[str, Any]],
) -> tuple[bool, str]:
    """Hostile per-assertion validator. Returns (is_valid_PASS, reason)."""
    if assertion["assertion_result"] != "PASS":
        return (False, f"assertion_result={assertion['assertion_result']}")
    allowed_ctrls = set(req.get("required_controls", [])) | set(
        req.get("supplemental_controls", [])
    )
    if assertion["control"] not in allowed_ctrls:
        return (False, f"control {assertion['control']!r} not in required/supplemental")
    if assertion["generated_by_command"] not in req.get("allowed_verifier_commands", []):
        return (
            False,
            f"generated_by_command {assertion['generated_by_command']!r} "
            f"not in allowed_verifier_commands",
        )
    if assertion["artifact_class"] not in req.get("allowed_artifact_classes", []):
        return (
            False,
            f"artifact_class {assertion['artifact_class']!r} "
            f"not in allowed_artifact_classes",
        )
    if not assertion.get("row_specific"):
        return (False, "row_specific=false")
    if not assertion.get("artifact_contains_control"):
        return (False, "artifact_contains_control=false")
    if not _freshness_ok(
        assertion["generated_at_utc"], int(assertion.get("freshness_hours", 168))
    ):
        return (
            False,
            f"assertion stale (generated {assertion['generated_at_utc']}, "
            f"window {assertion['freshness_hours']}h)",
        )
    # Artifact exists + re-hash
    art_rel = assertion["artifact_path"]
    art_abs = REPO_ROOT / art_rel
    if not art_abs.exists():
        return (False, f"artifact missing on disk: {art_rel}")
    cached = artifact_cache.get(art_rel)
    if cached is None:
        actual_sha = sha256_file(art_abs)
        parsed: Any = None
        try:
            parsed = json.loads(art_abs.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, UnicodeDecodeError):
            parsed = None
        artifact_cache[art_rel] = (actual_sha, parsed)
    actual_sha, parsed = artifact_cache[art_rel]
    if actual_sha != assertion["artifact_sha256"]:
        return (
            False,
            f"artifact sha256 mismatch: expected {assertion['artifact_sha256'][:12]}, "
            f"got {actual_sha[:12]}",
        )
    # Row-specificity (app-keyed for apps_e2e)
    ok, reason = _row_specificity_ok(assertion, req, parsed)
    if not ok:
        return (False, reason)
    return (True, "")


# =============================================================================
# Canary self-assertion
# =============================================================================

def _make_canary_assertion(
    catalog_sha: str, now_iso: str, reqs_path: Path
) -> dict[str, Any]:
    """Compiler-self-emitted PASS assertion for APPS-REQ-001.

    Shape mirrors the emitter's output so the standard validator can chew it.
    artifact_path is derived from reqs_path relative to REPO_ROOT so tests
    with tmp-path workspaces work correctly.
    """
    req_id = "APPS-REQ-001"
    control = "catalog_self_consistency"
    pointer = "/positive_control_req_id"
    try:
        artifact_rel = reqs_path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        artifact_rel = reqs_path.name
    h = hashlib.sha256(
        f"{req_id}|{control}|{catalog_sha}|{pointer}".encode("utf-8")
    ).hexdigest()
    return {
        "assertion_id": f"ASRT-{h[:40]}",
        "req_id": req_id,
        "control": control,
        "assertion_result": "PASS",
        "assertion_class": "APPS_POSITIVE_CONTROL_ASSERTION",
        "generated_by_command": COMPILER_PATH_REL,
        "verifier_exit_code": 0,
        "verifier_version": COMPILER_VERSION,
        "generated_at_utc": now_iso,
        "artifact_path": artifact_rel,
        "artifact_sha256": catalog_sha,
        "artifact_class": "APPS_CATALOG_SELF_REPORT",
        "artifact_payload_pointer": pointer,
        "artifact_contains_req_id": True,
        "artifact_contains_control": True,
        "row_specific": True,
        "freshness_hours": 168,
        "proof_payload": {
            "extracted_value": "PASS",
            "expected_value": "PASS",
            "match": True,
            "notes": "Compiler self-emitted canary. Catalog invariants passed.",
        },
        "app_name": None,
    }


