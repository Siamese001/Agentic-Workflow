# Main
# =============================================================================

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=OUTPUT_DIR)
    parser.add_argument("--reqs", type=Path, default=REQS_PATH)
    parser.add_argument("--assertions", type=Path, default=ASSERTIONS_PATH)
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    try:
        report = compile_report(args.reqs, args.assertions)
    except CompileError as e:
        print(f"FATAL: {e}", file=sys.stderr)
        return 2

    args.out_dir.mkdir(parents=True, exist_ok=True)
    report_path = args.out_dir / REPORT_PATH.name
    sha_path = args.out_dir / SHA256_PATH.name
    merkle_path = args.out_dir / MERKLE_PATH.name

    report_path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    report_sha = sha256_file(report_path)
    sha_path.write_text(f"{report_sha}  {report_path.name}\n", encoding="utf-8")

    merkle = build_merkle(report["rows"])
    merkle_path.write_text(
        json.dumps(merkle, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    s = report["summary"]
    if not args.quiet:
        print(
            f"[compile_apps_e2e_signoff] {s['total']} reqs; "
            f"signed_off={s['signed_off']} with_waiver={s['signed_off_with_waiver']} "
            f"blocked={s['blocked']} not_verified={s['not_verified']}"
        )
        print(f"  trust_level:        {report['trust_level']}")
        print(f"  positive_control:   {report['positive_control_status']}")
        print(f"  merkle root:        {merkle['root']}")
        print(f"  report sha256:      {report_sha}")

    return 0 if report["trust_level"] != "FAILED" else 1


if __name__ == "__main__":
    sys.exit(main())
