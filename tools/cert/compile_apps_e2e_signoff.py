# Main compile
# =============================================================================

def compile_report(
    reqs_path: Path = REQS_PATH,
    assertions_path: Path = ASSERTIONS_PATH,
) -> dict[str, Any]:
    if not reqs_path.exists():
        raise CompileError(f"catalog missing at {reqs_path}")
    if not assertions_path.exists():
        raise CompileError(f"assertions jsonl missing at {assertions_path}")

    # Load + schema-validate catalog.
    catalog = json.loads(reqs_path.read_text(encoding="utf-8"))
    reqs_schema = _load_schema(REQS_SCHEMA)
    errors = sorted(reqs_schema.iter_errors(catalog), key=lambda e: list(e.path))
    if errors:
        msgs = "; ".join(e.message for e in errors[:5])
        raise CompileError(f"catalog fails schema: {msgs}")
    reqs = catalog["requirements"]

    # Canary invariant check \u2014 compiler health proof.
    canary_violations = check_catalog_self_consistency(catalog)

    # Load + schema-validate every assertion.
    assertion_schema = _load_schema(ASSERTION_SCHEMA)
    assertions: list[dict[str, Any]] = []
    seen_aids: set[str] = set()
    schema_violations: list[tuple[int, str]] = []
    req_ids = {r["req_id"] for r in reqs}

    with assertions_path.open("r", encoding="utf-8") as f:
        for lineno, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError as e:
                schema_violations.append((lineno, f"unparseable JSON: {e}"))
                continue
            vs = list(assertion_schema.iter_errors(obj))
            if vs:
                schema_violations.append((lineno, f"schema: {vs[0].message}"))
                continue
            if obj["assertion_id"] in seen_aids:
                raise CompileError(f"duplicate assertion_id: {obj['assertion_id']}")
            seen_aids.add(obj["assertion_id"])
            if obj["req_id"] not in req_ids:
                schema_violations.append(
                    (lineno, f"assertion for unknown req_id {obj['req_id']}")
                )
                continue
            assertions.append(obj)

    # Inject compiler-self-emitted canary assertion iff invariants hold.
    now_iso = _iso_now()
    catalog_sha = sha256_file(reqs_path)
    if not canary_violations:
        canary_assertion = _make_canary_assertion(catalog_sha, now_iso, reqs_path)
        if canary_assertion["assertion_id"] not in seen_aids:
            assertions.append(canary_assertion)
            seen_aids.add(canary_assertion["assertion_id"])

    # Index.
    by_req_ctrl: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for a in assertions:
        by_req_ctrl.setdefault((a["req_id"], a["control"]), []).append(a)

    # Evaluate each requirement.
    artifact_cache: dict[str, tuple[str, Any]] = {}
    rows: list[dict[str, Any]] = []

    for req in reqs:
        rid = req["req_id"]
        required = req.get("required_controls", [])
        is_waiver = req["claim_type"] in WAIVER_CLAIM_TYPES
        control_evals: list[dict[str, Any]] = []
        missing_any = False
        had_any_evidence = False

        for ctrl in required:
            candidates = by_req_ctrl.get((rid, ctrl), [])
            had_any_evidence = had_any_evidence or bool(candidates)

            if not candidates:
                missing_any = True
                control_evals.append(
                    {
                        "name": ctrl,
                        "passed": False,
                        "reason": "no assertion for this control",
                        "assertion_id": None,
                        "artifact_path": None,
                        "artifact_sha256": None,
                    }
                )
                continue

            chosen = None
            last_reason = ""
            for a in candidates:
                ok, reason = validate_assertion(a, req, artifact_cache)
                if ok:
                    chosen = a
                    break
                last_reason = reason

            if chosen is not None:
                control_evals.append(
                    {
                        "name": ctrl,
                        "passed": True,
                        "reason": None,
                        "assertion_id": chosen["assertion_id"],
                        "artifact_path": chosen["artifact_path"],
                        "artifact_sha256": chosen["artifact_sha256"],
                    }
                )
            else:
                missing_any = True
                control_evals.append(
                    {
                        "name": ctrl,
                        "passed": False,
                        "reason": last_reason or "no valid PASS assertion",
                        "assertion_id": candidates[0]["assertion_id"],
                        "artifact_path": candidates[0]["artifact_path"],
                        "artifact_sha256": candidates[0]["artifact_sha256"],
                    }
                )

        # Row status.
        if not missing_any and control_evals:
            status = "SIGNED_OFF_WITH_WAIVER" if is_waiver else "SIGNED_OFF"
            blocking_gap = None
        elif had_any_evidence:
            status = "BLOCKED"
            first_failing = next((c for c in control_evals if not c["passed"]), None)
            blocking_gap = (
                f"{first_failing['name']}: {first_failing['reason']}"
                if first_failing else "unknown"
            )
        else:
            status = "NOT_VERIFIED"
            blocking_gap = "no atomic assertion provided for required controls"

        assertion_ids = sorted({c["assertion_id"] for c in control_evals if c["assertion_id"]})
        row = {
            "req_id": rid,
            "title": req.get("title", ""),
            "claim_type": req.get("claim_type", ""),
            "priority": req.get("priority", ""),
            "requirement_group": req.get("requirement_group", ""),
            "is_final_hundred_percent_row": bool(req.get("is_final_hundred_percent_row", False)),
            "is_positive_control": bool(req.get("is_positive_control", False)),
            "owner_app": req.get("owner_app"),
            "depends_on_req_ids": list(req.get("depends_on_req_ids", [])),
            "required_controls": list(required),
            "computed_status": status,
            "blocking_gap": blocking_gap,
            "controls": control_evals,
            "assertion_ids": assertion_ids,
            "row_evidence_sha256": "",
            "row_digest": "",
            "evaluated_at_utc": now_iso,
        }
        rows.append(row)

    # depends_on_req_ids gate \u2014 block any row whose dep is not SIGNED_OFF(_WITH_WAIVER).
    def _is_ok(status: str) -> bool:
        return status in ("SIGNED_OFF", "SIGNED_OFF_WITH_WAIVER")

    status_by_id = {r["req_id"]: r["computed_status"] for r in rows}
    for row in rows:
        if not _is_ok(row["computed_status"]):
            continue
        for dep in row["depends_on_req_ids"]:
            if not _is_ok(status_by_id.get(dep, "MISSING")):
                row["computed_status"] = "BLOCKED"
                row["blocking_gap"] = (
                    f"depends_on {dep} (status={status_by_id.get(dep, 'MISSING')})"
                )
                break
    # Refresh status_by_id after deps pass.
    status_by_id = {r["req_id"]: r["computed_status"] for r in rows}

    # Per-row digests (run-independent).
    EXCLUDE = {"evaluated_at_utc", "row_digest", "row_evidence_sha256"}
    for row in rows:
        evidence_input = {
            "req_id": row["req_id"],
            "status": row["computed_status"],
            "blocking_gap": row["blocking_gap"],
            "controls": row["controls"],
            "required_controls": row["required_controls"],
            "depends_on_req_ids": row["depends_on_req_ids"],
        }
        row["row_evidence_sha256"] = sha256_json_canonical(evidence_input)
        digest_input = {k: v for k, v in row.items() if k not in EXCLUDE}
        row["row_digest"] = sha256_json_canonical(digest_input)

    # Summary.
    total = len(rows)
    signed_off = sum(1 for r in rows if r["computed_status"] == "SIGNED_OFF")
    signed_off_waiver = sum(1 for r in rows if r["computed_status"] == "SIGNED_OFF_WITH_WAIVER")
    blocked = sum(1 for r in rows if r["computed_status"] == "BLOCKED")
    not_verified = sum(1 for r in rows if r["computed_status"] == "NOT_VERIFIED")

    by_claim_type: dict[str, dict[str, int]] = collections.defaultdict(
        lambda: {"total": 0, "signed_off": 0, "signed_off_with_waiver": 0, "blocked": 0, "not_verified": 0}
    )
    for row in rows:
        ct = row["claim_type"] or "UNKNOWN"
        by_claim_type[ct]["total"] += 1
        status = row["computed_status"]
        if status == "SIGNED_OFF":
            by_claim_type[ct]["signed_off"] += 1
        elif status == "SIGNED_OFF_WITH_WAIVER":
            by_claim_type[ct]["signed_off_with_waiver"] += 1
        elif status == "BLOCKED":
            by_claim_type[ct]["blocked"] += 1
        else:
            by_claim_type[ct]["not_verified"] += 1

    canary_row = next((r for r in rows if r["is_positive_control"]), None)
    canary_status = (canary_row or {}).get("computed_status", "MISSING")

    assertions_sha = sha256_file(assertions_path)
    row_digest_all = sha256_json_canonical(
        [r["row_digest"] for r in sorted(rows, key=lambda x: x["req_id"])]
    )
    evidence_digest_all = sha256_json_canonical(
        [r["row_evidence_sha256"] for r in sorted(rows, key=lambda x: x["req_id"])]
    )
    git_commit, git_dirty = _git_state()

    percent = round(
        100.0 * (signed_off + signed_off_waiver) / max(1, total), 1
    )

    report: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "compiler_version": COMPILER_VERSION,
        "compiler_path": COMPILER_PATH_REL,
        "compiler_sha256": sha256_file(Path(__file__)),
        "run_timestamp_utc": now_iso,
        "source_repo_root": str(REPO_ROOT).replace("\\", "/"),
        "git_commit": git_commit,
        "git_dirty": git_dirty,
        "requirements_source_sha256": catalog_sha,
        "evidence_assertions_sha256": assertions_sha,
        "row_digest": row_digest_all,
        "evidence_digest": evidence_digest_all,
        "rows": sorted(rows, key=lambda r: r["req_id"]),
        "summary": {
            "total": total,
            "signed_off": signed_off,
            "signed_off_with_waiver": signed_off_waiver,
            "blocked": blocked,
            "not_verified": not_verified,
            "percent_signed_off": percent,
            "by_claim_type": dict(by_claim_type),
            "canary_status": canary_status,
        },
        "positive_control_status": "PASS" if canary_status in ("SIGNED_OFF", "SIGNED_OFF_WITH_WAIVER") else "FAIL",
        "trust_level": "DEVELOPMENT_PROOF",
    }

    # Schema validation.
    report_schema = _load_schema(REPORT_SCHEMA)
    report_errs = list(report_schema.iter_errors(report))
    if report_errs:
        report["trust_level"] = "FAILED"
        report["schema_errors"] = [str(e.message) for e in report_errs[:10]]
        return report

    # Trust level (pre-signature).
    all_ok_or_waiver = (blocked + not_verified) == 0 and total > 0
    if not all_ok_or_waiver:
        report["trust_level"] = "DEVELOPMENT_PROOF"
    elif signed_off_waiver > 0:
        report["trust_level"] = "SIGNED_OFF_WITH_WAIVERS"
    else:
        report["trust_level"] = "INTEGRITY_PROOF"
    # W5 will upgrade to SIGNED_PROOF after signature verification.

    return report


# =============================================================================
# Merkle
# =============================================================================

def build_merkle(rows: list[dict[str, Any]]) -> dict[str, Any]:
    sorted_rows = sorted(rows, key=lambda r: r["req_id"])
    leaves = [{"req_id": r["req_id"], "leaf_hash": r["row_digest"]} for r in sorted_rows]

    def _pair(a: str, b: str) -> str:
        return sha256_bytes(bytes.fromhex(a) + bytes.fromhex(b))

    level = [L["leaf_hash"] for L in leaves]
    if not level:
        root = ""
    else:
        while len(level) > 1:
            if len(level) % 2 == 1:
                level.append(level[-1])
            level = [_pair(level[i], level[i + 1]) for i in range(0, len(level), 2)]
        root = level[0]

    return {
        "root": root,
        "leaf_count": len(leaves),
        "leaves": leaves,
        "computed_at_utc": _iso_now(),
        "algorithm": "sha256 pairwise, odd-node duplication",
        "schema_version": SCHEMA_VERSION,
    }


