#!/usr/bin/env python3
"""Direct check of Key 29 and Key 30 by running validator logic."""

import sys
import ast
from pathlib import Path

# Setup
ROOT = Path('.')
MAX_FUNCTION_LINES = 100
MAX_NESTING_DEPTH = 5

SOVEREIGN_DIRS = {
    "agentic_core", "apps_lic", "apps_rg", "apps_shared",
    "schemas", "prompt_governance", "observability", "config",
    "shared", "scripts"
}

def iter_sovereign_py_files():
    """Iterate over all Python files in sovereign directories."""
    for d in SOVEREIGN_DIRS:
        dir_path = ROOT / d
        if dir_path.exists():
            for f in dir_path.rglob("*.py"):
                if '__pycache__' not in str(f):
                    yield f

def is_generated_file(f):
    """Check if file is auto-generated."""
    try:
        content = f.read_text(encoding='utf-8')
        first_lines = content[:500].lower()
        return 'auto-generated' in first_lines or 'autogenerated' in first_lines
    except:
        return False

def compute_nesting_depth(node, current_depth=0):
    """Compute maximum nesting depth of a node."""
    max_depth = current_depth
    
    # Nodes that increase nesting depth
    nesting_nodes = (
        ast.If, ast.For, ast.While, ast.With, ast.Try,
        ast.ExceptHandler, ast.FunctionDef, ast.AsyncFunctionDef
    )
    
    for child in ast.iter_child_nodes(node):
        if isinstance(child, nesting_nodes):
            child_depth = compute_nesting_depth(child, current_depth + 1)
            max_depth = max(max_depth, child_depth)
        else:
            child_depth = compute_nesting_depth(child, current_depth)
            max_depth = max(max_depth, child_depth)
    
    return max_depth

# Check Key 29
print("="*70)
print("KEY 29: Function Length Check (>100 lines)")
print("="*70)

key29_violations = []
for f in iter_sovereign_py_files():
    if is_generated_file(f):
        continue
    try:
        tree = ast.parse(f.read_text(encoding='utf-8'))
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if hasattr(node, "end_lineno") and node.end_lineno:
                    lines = node.end_lineno - node.lineno + 1
                    if lines > MAX_FUNCTION_LINES:
                        key29_violations.append(
                            f"{f.relative_to(ROOT)}:{node.lineno} – {node.name} ({lines} lines)"
                        )
    except:
        pass

if key29_violations:
    print(f"\nFOUND {len(key29_violations)} VIOLATIONS:")
    for v in key29_violations[:20]:
        print(f"  - {v}")
    if len(key29_violations) > 20:
        print(f"  ... and {len(key29_violations) - 20} more")
else:
    print("\n✓ PASS: All functions within 100 line limit")

# Check Key 30
print("\n" + "="*70)
print("KEY 30: Nesting Depth Check (>5 levels)")
print("="*70)

key30_violations = []
for f in iter_sovereign_py_files():
    if is_generated_file(f):
        continue
    try:
        tree = ast.parse(f.read_text(encoding='utf-8'))
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                depth = compute_nesting_depth(node, 0)
                if depth > MAX_NESTING_DEPTH:
                    key30_violations.append(
                        f"{f.relative_to(ROOT)}:{node.lineno} – {node.name} (depth {depth})"
                    )
    except:
        pass

if key30_violations:
    print(f"\nFOUND {len(key30_violations)} VIOLATIONS:")
    for v in key30_violations[:20]:
        print(f"  - {v}")
    if len(key30_violations) > 20:
        print(f"  ... and {len(key30_violations) - 20} more")
else:
    print("\n✓ PASS: All functions within depth 5 limit")

print("\n" + "="*70)
print(f"SUMMARY: Key 29 ({len(key29_violations)} violations), Key 30 ({len(key30_violations)} violations)")
print("="*70)
